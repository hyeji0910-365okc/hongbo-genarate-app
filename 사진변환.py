from datetime import date, datetime
from pathlib import Path

from PIL import Image, ImageDraw, ImageOps

크기 = 1080
기준폴더 = Path(__file__).parent
자료폴더 = 기준폴더 / "자료"
완성폴더 = 기준폴더 / "완성"
로고_비율 = 0.15   # 사진 가로 폭 대비 로고 크기
로고_여백 = 40     # 사진 가장자리에서 안쪽으로 띄우는 거리


def 가운데_정사각형으로_자르기(사진):
    가로, 세로 = 사진.size
    짧은변 = min(가로, 세로)
    왼쪽 = (가로 - 짧은변) // 2
    위쪽 = (세로 - 짧은변) // 2
    return 사진.crop((왼쪽, 위쪽, 왼쪽 + 짧은변, 위쪽 + 짧은변))


def 로고_찾기():
    for 폴더 in (기준폴더, 자료폴더):
        for 이름 in ("로고_투명.png", "로고.jpg", "로고.jpeg", "로고.png"):
            if (폴더 / 이름).is_file():
                return 폴더 / 이름
    return None


def 로고_준비(경로):
    """흰 바탕과 빛 번짐은 투명하게 지우고, 로고 모양만 남겨 사진 크기에 맞게 줄인다. 실패하면 None."""
    try:
        with Image.open(경로) as 원본:
            로고 = 원본.convert("RGBA")
        if 로고.getextrema()[3][0] < 255:   # 이미 투명 배경이 있는 로고
            투명도 = 로고.getchannel("A")
        else:
            밝기 = 로고.convert("L")
            투명도 = 밝기.point(lambda v: max(0, min(255, round((172 - v) * 255 / 30))))
        상자 = 투명도.point(lambda v: 255 if v > 128 else 0).getbbox()
        if not 상자:
            return None
        로고.putalpha(투명도)
        로고 = 로고.crop(상자)
        너비 = round(크기 * 로고_비율)
        높이 = max(1, round(로고.height * 너비 / 로고.width))
        return 로고.resize((너비, 높이), Image.LANCZOS)
    except Exception:
        return None


def 로고_넣기(사진, 로고):
    """오른쪽 아래에 투명한 흰 사각형을 깔고 그 위에 로고를 올린다."""
    안쪽 = 12
    카드너비, 카드높이 = 로고.width + 안쪽 * 2, 로고.height + 안쪽 * 2
    x = 크기 - 로고_여백 - 카드너비
    y = 크기 - 로고_여백 - 카드높이

    카드 = Image.new("L", 사진.size, 0)
    ImageDraw.Draw(카드).rounded_rectangle(
        (x, y, x + 카드너비, y + 카드높이), radius=6, fill=150)
    사진.paste((255, 255, 255), mask=카드)
    사진.paste(로고, (x + 안쪽, y + 안쪽), 로고)
    return 사진


def 새_폴더_만들기():
    """실행할 때마다 '완성' 안에 날짜_시각 이름의 새 폴더를 만든다."""
    이름 = datetime.now().strftime("%Y-%m-%d_%H시%M분")
    폴더 = 완성폴더 / 이름
    덧붙임 = 2
    while 폴더.exists():
        폴더 = 완성폴더 / f"{이름}_{덧붙임}"
        덧붙임 += 1
    폴더.mkdir(parents=True)
    return 폴더


def 다음_번호(폴더, 접두어):
    번호들 = []
    for 파일 in 폴더.glob(f"{접두어}_*.jpg"):
        뒷부분 = 파일.stem.split("_")[-1]
        if 뒷부분.isdigit():
            번호들.append(int(뒷부분))
    return max(번호들, default=0) + 1


def 파일_읽기(*경로들):
    for 경로 in 경로들:
        if 경로.is_file():
            return 경로.read_text(encoding="utf-8-sig").strip()
    return None


def 받침있음(글자):
    return (ord(글자) - 0xAC00) % 28 != 0


def 조사(말, 받침있을때, 받침없을때):
    return 받침있을때 if 말 and 받침있음(말[-1]) else 받침없을때


def 관형(말):
    """'조용한 자리 많음' -> '조용한 자리 많은' 처럼 뒤에 명사가 올 수 있게 바꾼다."""
    if 말.endswith("음"):
        return 말[:-1] + "은"
    if 말.endswith("함"):
        return 말[:-1] + "한"
    return 말


def 가게정보_읽기(글):
    """가게 정보.txt를 항목별로 나눈다."""
    정보 = {"홍보": []}
    홍보중 = False
    for 줄 in 글.splitlines():
        줄 = 줄.strip()
        if not 줄:
            continue
        if 줄.startswith("이번 주 홍보"):
            홍보중 = True
        elif 줄.startswith("-") and 홍보중:
            정보["홍보"].append(줄.lstrip("- ").strip())
        elif ":" in 줄:
            이름, 내용 = (조각.strip() for 조각 in 줄.split(":", 1))
            홍보중 = False
            정보[이름] = 내용
    return 정보


